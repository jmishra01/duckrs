#!/usr/bin/env python3
"""Generates crates/duckrs-core/src/client/settings_table.rs from the DuckDB checkout.

The settings come from duckdb/src/common/settings.json, which DuckDB's own
scripts/generate_settings.py turns into C++; the extra aliases are the
DUCKDB_SETTING_ALIAS entries of duckdb/src/main/config.cpp.

    python3 tools/generate_settings.py [../duckdb]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DUCKDB = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "duckdb")
OUTPUT = ROOT / "crates/duckrs-core/src/client/settings_table.rs"


def struct_name(setting):
    if "struct" in setting:
        return setting["struct"]
    return "".join(part.capitalize() for part in setting["name"].split("_")) + "Setting"


def scope(setting):
    # settings with a default value can be set in both scopes and say which one is the default;
    # the others say the only scope they can be set in
    if "default_scope" in setting:
        return {"global": "GlobalDefault", "local": "LocalDefault"}[setting["default_scope"]]
    return {"global": "GlobalOnly", "local": "LocalOnly"}[setting["scope"]]


def input_type(setting):
    # enum settings take their value as a string, like ParseLogicalType of the C++ InputType
    return "VARCHAR" if setting["type"].startswith("ENUM<") else setting["type"]


def rust_string(text):
    return json.dumps(text)


def main():
    settings = json.loads((DUCKDB / "src/common/settings.json").read_text())
    aliases = {s["name"]: list(s.get("aliases", [])) for s in settings}
    by_struct = {struct_name(s): s["name"] for s in settings}
    config = (DUCKDB / "src/main/config.cpp").read_text()
    for alias, struct in re.findall(r'DUCKDB_SETTING_ALIAS\("([^"]+)",\s*(\w+)\)', config):
        name = by_struct.get(struct)
        if name is not None and alias not in aliases[name]:
            aliases[name].append(alias)
    lines = [
        "// @generated by tools/generate_settings.py from duckdb/src/common/settings.json and the",
        "// setting aliases of duckdb/src/main/config.cpp @ rust-port-baseline. Do not edit.",
        "",
        "use super::settings::{SettingDefinition, SettingScope};",
        "",
        "pub(super) static SETTINGS: &[SettingDefinition] = &[",
    ]
    for s in sorted(settings, key=lambda s: s["name"]):
        default = s.get("default_value")
        lines += [
            "    SettingDefinition {",
            f"        name: {rust_string(s['name'])},",
            f"        aliases: &[{', '.join(rust_string(a) for a in aliases[s['name']])}],",
            f"        input_type: {rust_string(input_type(s))},",
            f"        scope: SettingScope::{scope(s)},",
            f"        default_value: {'None' if default is None else 'Some(' + rust_string(str(default)) + ')'},",
            "    },",
        ]
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(settings)} settings to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
