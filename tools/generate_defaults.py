#!/usr/bin/env python3
"""Generates crates/pintail-core/src/catalog/defaults_table.rs from the DuckDB checkout.

The default views, macros and table macros are SQL in the initializer arrays of
duckdb/src/catalog/default/default_{views,functions,table_functions}.cpp; this reads those
arrays and writes them out as Rust.

    python3 tools/generate_defaults.py [../duckdb]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DUCKDB = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "duckdb")
OUTPUT = ROOT / "crates/pintail-core/src/catalog/defaults_table.rs"

ESCAPES = {"n": "\n", "t": "\t", '"': '"', "'": "'", "\\": "\\", "r": "\r", "0": "\0"}


def tokenize(text):
    """The tokens of a C++ initializer: braces, commas, strings (adjacent literals joined), names."""
    i, tokens = 0, []
    while i < len(text):
        c = text[i]
        if text.startswith("//", i):
            i = text.index("\n", i)
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2
        elif c.isspace():
            i += 1
        elif text.startswith('R"(', i):
            end = text.index(')"', i + 3)
            tokens.append(("str", text[i + 3 : end]))
            i = end + 2
        elif c == '"':
            j, out = i + 1, []
            while text[j] != '"':
                if text[j] == "\\":
                    out.append(ESCAPES[text[j + 1]])
                    j += 2
                else:
                    out.append(text[j])
                    j += 1
            tokens.append(("str", "".join(out)))
            i = j + 1
        elif c in "{},":
            tokens.append((c, c))
            i += 1
            depth = sum(1 for t in tokens if t[0] == "{") - sum(1 for t in tokens if t[0] == "}")
            if c == "}" and depth == 0:
                break
        else:
            m = re.match(r"[A-Za-z_][A-Za-z0-9_:]*", text[i:])
            if not m:
                raise ValueError(f"unexpected {text[i:i+20]!r}")
            tokens.append(("name", m.group(0)))
            i += m.end()
    joined = []
    for token in tokens:
        if token[0] == "str" and joined and joined[-1][0] == "str":
            joined[-1] = ("str", joined[-1][1] + token[1])
        else:
            joined.append(token)
    return joined


def parse(tokens, pos=0):
    """A braced list into nested Python lists; names map to None for nullptr."""
    assert tokens[pos][0] == "{"
    pos += 1
    items = []
    while tokens[pos][0] != "}":
        kind, value = tokens[pos]
        if kind == "{":
            item, pos = parse(tokens, pos)
        elif kind == "str":
            item, pos = value, pos + 1
        elif kind == "name":
            item = {"nullptr": None, "DEFAULT_SCHEMA": "main"}.get(value, value)
            pos += 1
        else:
            raise ValueError(f"unexpected {kind}")
        items.append(item)
        if tokens[pos][0] == ",":
            pos += 1
    return items, pos + 1


def array(path, name):
    text = path.read_text()
    start = text.index("{", text.index(name))
    items, _ = parse(tokenize(text[start:]), 0)
    return [item for item in items if item and item[0] is not None]


def rust(text):
    return json.dumps(text) if text is not None else "None"


def main():
    views = array(DUCKDB / "src/catalog/default/default_views.cpp", "internal_views[]")
    macros = array(DUCKDB / "src/catalog/default/default_functions.cpp", "internal_macros[]")
    table_macros = array(DUCKDB / "src/catalog/default/default_table_functions.cpp", "internal_table_macros[]")
    lines = [
        "// @generated by tools/generate_defaults.py from",
        "// duckdb/src/catalog/default/default_{views,functions,table_functions}.cpp @ rust-port-baseline.",
        "// Do not edit.",
        "",
        "/// `internal_views`: (schema, name, query).",
        "pub(super) static VIEWS: &[(&str, &str, &str)] = &[",
    ]
    for schema, name, sql in views:
        lines.append(f"    ({rust(schema)}, {rust(name)}, {rust(sql)}),")
    lines += ["];", "", "/// `internal_macros`: (schema, name, the macro after its name).", "pub(super) static MACROS: &[(&str, &str, &str)] = &["]
    for schema, name, body in macros:
        lines.append(f"    ({rust(schema)}, {rust(name)}, {rust(body)}),")
    lines += [
        "];",
        "",
        "/// `internal_table_macros`: (schema, name, parameters, named parameters with defaults, query).",
        "#[allow(clippy::type_complexity)]",
        "pub(super) static TABLE_MACROS: &[(&str, &str, &[&str], &[(&str, &str)], &str)] = &[",
    ]
    for schema, name, params, named, body in table_macros:
        params = ", ".join(rust(p) for p in params if p is not None)
        named = ", ".join(f"({rust(k)}, {rust(v)})" for k, v in (n for n in named if n and n[0] is not None))
        lines.append(f"    ({rust(schema)}, {rust(name)}, &[{params}], &[{named}], {rust(body)}),")
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(views)} views, {len(macros)} macros, {len(table_macros)} table macros")


if __name__ == "__main__":
    main()
