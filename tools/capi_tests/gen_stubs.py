#!/usr/bin/env python3
"""Lists the functions of duckdb.h, and writes weak stubs for those a library does not export.

usage: gen_stubs.py list <duckdb.h>
       gen_stubs.py stubs <duckdb.h> <exported-symbols.txt> <out.cpp>

A stub throws std::runtime_error("duckrs: <name> is not implemented"), so a Catch2 test case that
calls a function duckrs does not have yet fails on its own instead of breaking the build.
"""
import re
import subprocess
import sys


def declarations(header):
    text = subprocess.run(
        ["clang", "-E", "-P", "-x", "c++", "-DDUCKDB_C_API=__capi_mark__", header],
        check=True, capture_output=True, text=True).stdout
    text = re.sub(r"\s+", " ", text)
    out = []
    for m in re.finditer(r"__capi_mark__ ([^;{}]*?)\b(duckdb_\w+)\s*\(([^;{}]*)\)\s*;", text):
        ret, name, params = m.group(1).strip(), m.group(2), m.group(3).strip()
        ret = re.sub(r"__attribute__\s*\(\(\s*deprecated(\(\"[^\"]*\"\))?\s*\)\)", "", ret).strip()
        out.append((ret, name, params))
    return out


def main():
    if sys.argv[1] == "list":
        for ret, name, params in declarations(sys.argv[2]):
            print(name)
        return
    header, exported, target = sys.argv[2:5]
    have = set()
    with open(exported) as f:
        for line in f:
            have.add(line.strip().lstrip("_"))
    lines = [
        "// Generated by tools/capi_tests/gen_stubs.py: the duckdb.h functions libduckrs_capi does not export yet.",
        "#include \"duckdb.h\"",
        "#include <stdexcept>",
        "extern \"C\" {",
    ]
    missing = 0
    for ret, name, params in declarations(header):
        if name in have:
            continue
        missing += 1
        lines.append(f"__attribute__((weak)) {ret} {name}({params}) {{")
        lines.append(f"\tthrow std::runtime_error(\"duckrs: {name} is not implemented\");")
        lines.append("}")
    lines.append("}")
    with open(target, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{missing} of {len(declarations(header))} functions stubbed", file=sys.stderr)


main()
