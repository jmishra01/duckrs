//! Summaries, `STATUS.md` generation, and the known-passing regression gate.

use crate::runner::{FileReport, Outcome};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

#[derive(Debug, Default, Clone, Copy)]
pub struct Counts {
    pub files: usize,
    pub pass: usize,
    pub fail: usize,
    pub skip: usize,
    pub error: usize,
    pub executed: usize,
    pub passed_statements: usize,
}

impl Counts {
    fn add(&mut self, r: &FileReport) {
        self.files += 1;
        match r.outcome {
            Outcome::Pass => self.pass += 1,
            Outcome::Fail { .. } => self.fail += 1,
            Outcome::Skip(_) => self.skip += 1,
            Outcome::Error(_) => self.error += 1,
        }
        self.executed += r.executed;
        self.passed_statements += r.passed;
    }

    /// Pass rate over files that ran (skipped files excluded).
    pub fn pass_rate(&self) -> f64 {
        let ran = self.files - self.skip;
        if ran == 0 {
            0.0
        } else {
            100.0 * self.pass as f64 / ran as f64
        }
    }
}

pub fn totals(reports: &[FileReport]) -> Counts {
    let mut c = Counts::default();
    reports.iter().for_each(|r| c.add(r));
    c
}

/// Groups reports by directory, e.g. `test/sql/aggregate/aggregates/x.test` → `test/sql/aggregate`.
fn group_key(path: &str, depth: usize) -> String {
    let parts: Vec<&str> = path.split('/').collect();
    let keep = depth.min(parts.len().saturating_sub(1)).max(1);
    parts[..keep].join("/")
}

pub fn status_markdown(engine: &str, baseline: &str, reports: &[FileReport]) -> String {
    let mut groups: BTreeMap<String, Counts> = BTreeMap::new();
    for r in reports {
        groups.entry(group_key(&r.path, 3)).or_default().add(r);
    }
    let total = totals(reports);
    let mut out = String::new();
    let _ = writeln!(out, "# sqllogictest status: `{engine}`\n");
    let _ = writeln!(out, "Generated by `tools/sqllogictest`. Do not edit by hand.\n");
    let _ = writeln!(out, "- Baseline: `{baseline}`");
    let _ = writeln!(
        out,
        "- Files: {} — pass {}, fail {}, skip {}, error {} (**{:.1}%** of files that ran)",
        total.files,
        total.pass,
        total.fail,
        total.skip,
        total.error,
        total.pass_rate()
    );
    let _ = writeln!(
        out,
        "- Statements executed: {}, passed: {}\n",
        total.executed, total.passed_statements
    );
    let _ = writeln!(out, "| Directory | Files | Pass | Fail | Skip | Error | Pass % |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---:|");
    for (dir, c) in &groups {
        let _ = writeln!(
            out,
            "| `{dir}` | {} | {} | {} | {} | {} | {:.1} |",
            c.files,
            c.pass,
            c.fail,
            c.skip,
            c.error,
            c.pass_rate()
        );
    }
    out
}

pub fn passing_list(reports: &[FileReport]) -> String {
    let mut paths: Vec<&str> = reports
        .iter()
        .filter(|r| r.outcome == Outcome::Pass)
        .map(|r| r.path.as_str())
        .collect();
    paths.sort_unstable();
    let mut out = String::from(
        "# Test files (relative to the DuckDB checkout) that pintail passes. CI fails if any of these\n\
         # stop passing. Regenerate with:\n\
         #   ./target/release/sqllogictest --allow-failures --passing-out tools/sqllogictest/known_passing.txt\n",
    );
    for p in paths {
        out.push_str(p);
        out.push('\n');
    }
    out
}

/// Files listed as known-passing that did not pass in this run.
pub fn regressions<'a>(known_passing: &'a str, reports: &[FileReport]) -> Vec<&'a str> {
    let passing: BTreeSet<&str> = reports
        .iter()
        .filter(|r| r.outcome == Outcome::Pass)
        .map(|r| r.path.as_str())
        .collect();
    let ran: BTreeSet<&str> = reports.iter().map(|r| r.path.as_str()).collect();
    known_passing
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter(|l| ran.contains(l) && !passing.contains(l))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::Duration;

    fn report(path: &str, outcome: Outcome) -> FileReport {
        FileReport {
            path: path.into(),
            outcome,
            executed: 1,
            passed: 1,
            mode_skipped: 0,
            duration: Duration::ZERO,
        }
    }

    #[test]
    fn groups_and_regressions() {
        let reports = vec![
            report("test/sql/select/a.test", Outcome::Pass),
            report("test/sql/select/b.test", Outcome::Skip("require x".into())),
            report("test/sql/join/c.test", Outcome::Error("boom".into())),
        ];
        let md = status_markdown("pintail", "abc", &reports);
        assert!(md.contains("| `test/sql/select` | 2 | 1 | 0 | 1 | 0 | 100.0 |"));
        let known = "test/sql/select/a.test\ntest/sql/join/c.test\ntest/sql/other.test\n";
        assert_eq!(regressions(known, &reports), ["test/sql/join/c.test"]);
        let list = passing_list(&reports);
        assert!(list.ends_with("\ntest/sql/select/a.test\n"));
        assert!(regressions(&list, &reports).is_empty());
    }
}
